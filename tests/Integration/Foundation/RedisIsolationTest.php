<?php

declare(strict_types=1);

use Tests\Support\IntegrationConnections;

function f03RedisConnections(): IntegrationConnections
{
    expect(is_callable([IntegrationConnections::class, 'current']))->toBeTrue();

    return IntegrationConnections::current();
}

it('authenticates real native Redis A and B separately and isolates equal logical keys', function (): void {
    $connections = f03RedisConnections();
    $token = $connections->token();
    $a = $connections->redis('a');
    $b = $connections->redis('b');
    $keyA = 'f03:'.$token.':a:same-logical-key';
    $keyB = 'f03:'.$token.':b:same-logical-key';
    try {
        expect($a)->toBeInstanceOf(Redis::class)->not->toBe($b);
        expect($b)->toBeInstanceOf(Redis::class);
        expect($a->rawCommand('ACL', 'WHOAMI'))->toBe('f03_'.$token.'_a_rt');
        expect($b->rawCommand('ACL', 'WHOAMI'))->toBe('f03_'.$token.'_b_rt');
        expect($a->ping())->toBeIn([true, 'PONG', '+PONG']);
        expect($b->ping())->toBeIn([true, 'PONG', '+PONG']);
        expect($a->set($keyA, 'synthetic-a'))->toBeTrue();
        expect($b->set($keyB, 'synthetic-b'))->toBeTrue();
        expect($a->get($keyA))->toBe('synthetic-a');
        expect($b->get($keyB))->toBe('synthetic-b');
        expect($a->del($keyA))->toBe(1);
        expect($a->get($keyA))->toBeFalse();
        expect($b->get($keyB))->toBe('synthetic-b');
    } finally {
        $a->del($keyA);
        $b->del($keyB);
        $a->close();
        $b->close();
    }
})->group('testing-foundation-integration');

it('requires actual NOPERM for cross-prefix GET SET and DEL in both directions', function (string $source, string $command): void {
    $connections = f03RedisConnections();
    $token = $connections->token();
    $target = $source === 'a' ? 'b' : 'a';
    $client = $connections->redis($source);
    $other = $connections->redis($target);
    $ownKey = 'f03:'.$token.':'.$source.':denial-probe';
    $targetKey = 'f03:'.$token.':'.$target.':denial-probe';
    try {
        expect($client->rawCommand('ACL', 'WHOAMI'))->toBe('f03_'.$token.'_'.$source.'_rt');
        expect($client->set($ownKey, 'own'))->toBeTrue();
        expect($other->set($targetKey, 'other'))->toBeTrue();
        $client->clearLastError();
        $reason = '';
        $result = false;
        try {
            $result = $command === 'SET'
                ? $client->rawCommand('SET', $targetKey, 'unexpected')
                : $client->rawCommand($command, $targetKey);
            $reason = (string) $client->getLastError();
        } catch (RedisException $error) {
            $reason = $error->getMessage();
        }
        // Do not print raw diagnostic messages: classify only actual NOPERM.
        expect($result)->toBeFalse();
        expect(str_contains(strtoupper($reason), 'NOPERM'))->toBeTrue();
        expect($other->get($targetKey))->toBe('other');
        expect($client->get($ownKey))->toBe('own');
    } finally {
        $client->del($ownKey);
        $other->del($targetKey);
        $client->close();
        $other->close();
    }
})->with(['a', 'b'])->with(['GET', 'SET', 'DEL'])->group('testing-foundation-integration');

it('requires actual owned setup version and admin ACL DRYRUN evidence without executing forbidden commands', function (): void {
    $connections = f03RedisConnections();
    // This metadata must be generated by the real owned setup step from
    // actual admin ACL DRYRUN checks, bound to the verified run identity.
    // The runtime tests never receive the admin credential or execute them.
    $evidence = $connections->redisSetupEvidence();
    expect($evidence['server_version'])->toBe('8.2.11');
    expect($evidence['token'])->toBe($connections->token());
    foreach (['a', 'b'] as $slot) {
        foreach (['FLUSHALL', 'FLUSHDB', 'CONFIG GET', 'ACL SETUSER', 'SELECT', 'EVAL', 'SHUTDOWN'] as $command) {
            expect($evidence['denials'][$slot][$command])->toBeTrue();
        }
    }
})->group('testing-foundation-integration');
